// Generates games/tambola/mount.cjs from the original ESM games/tambola/server.js.
// The game logic is copied through verbatim; only the module wrapper (imports, express
// bootstrap, listen) is replaced, so there is no hand-transcription to get wrong.
// Re-run this after editing server.js.
const fs = require('fs');
const path = require('path');

const GAME_DIR = path.join(__dirname, '..', 'games', 'tambola');
const SRC = path.join(GAME_DIR, 'server.js');
const OUT = path.join(GAME_DIR, 'mount.cjs');

const src = fs.readFileSync(SRC, 'utf8');

const HEAD_END = "app.get('*', (_, res) => res.sendFile(path.join(__dirname, 'dist/index.html')));";
const TAIL_START = "const PORT = process.env.PORT || 3001;";

const headAt = src.indexOf(HEAD_END);
const tailAt = src.indexOf(TAIL_START);
if (headAt === -1 || tailAt === -1 || tailAt < headAt) {
  console.error('FAILED: tambola/server.js is not in the expected shape.');
  process.exit(1);
}

const logic = src.slice(headAt + HEAD_END.length, tailAt).trim();

const HEADER = `// Tambola Queen — mounted inside MZeeGamingHub at BASE.
// GENERATED by scripts/build-tambola-mount.js from server.js — edit server.js, then re-run.
// The WebSocket server is created with noServer:true; the hub routes upgrades to it by path,
// so it can share one HTTP server with Business Tycoon's Socket.IO without either aborting
// the other's handshakes.
const express = require('express');
const path = require('path');
const { WebSocketServer } = require('ws');

const BASE = '/games/tambola';
const WS_PATH = BASE + '/ws';
// Vite builds straight into the hub's public tree, so static files are served by the hub.
const DIST = path.join(__dirname, '..', '..', 'public', 'games', 'tambola');

const app = express.Router();
const wss = new WebSocketServer({ noServer: true });

`;

const FOOTER = `

// Deep links inside the game fall back to its SPA entry point.
app.get('*', (req, res) => res.sendFile(path.join(DIST, 'index.html')));

module.exports = {
  base: BASE,
  wsPath: WS_PATH,
  router: app,
  wss,
  // Called by the hub's single 'upgrade' router.
  handleUpgrade(req, socket, head) {
    wss.handleUpgrade(req, socket, head, (ws) => wss.emit('connection', ws, req));
  }
};
`;

fs.writeFileSync(OUT, HEADER + logic + FOOTER);
console.log('generated games/tambola/mount.cjs (' + logic.split('\n').length + ' lines of game logic carried over)');
